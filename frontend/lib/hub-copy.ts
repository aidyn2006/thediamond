/**
 * Every word that ends up in a hub's <title>, description, H1, intro and FAQ, in both
 * languages.
 *
 * It lives apart from the components for the reason tar-toi's content modules do: the
 * copy is the product here, the JSX is just a frame. Keeping it in one file makes it
 * possible to read a whole page's Kazakh text end to end and catch the machine-translated
 * seams — which is exactly what these pages must not have.
 *
 * Every sentence is composed from checkable facts (counts, prices, cities, battery
 * averages). Nothing is invented, and each variant reads naturally when the catalog is
 * empty — an "0 объявлений" page is still a page a human might land on.
 *
 * Brand names stay latin in both languages ("iPhone" is typed the same way in Kazakh),
 * while `brandRuLabels` supplies the cyrillic spelling people also search with; that
 * spelling is shared, since "айфон" is typed identically in Russian and Kazakh.
 */

export interface HubQa {
  q: string;
  a: string;
}

export interface HubCopy {
  title: string;
  description: string;
  h1: string;
  intro: string;
  faqTitle: string;
  faq: HubQa[];
  /** Heading above the model chips. */
  modelsHeading: string;
}

